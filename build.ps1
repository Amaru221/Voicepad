param(
    [switch]$Clean
)

# VoicePad build script.
# Requires: Visual Studio with the "Desktop development with C++" workload
# (VS 2022 or VS 2026), and CMake. JUCE does NOT support MinGW.
#
# The generator is auto-detected from the installed Visual Studio. The script
# also detects a stale CMake cache built with a different generator and cleans
# it up automatically.

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$buildDir = Join-Path $root "build"
Push-Location $root
try {
    # --- Detect Visual Studio generator -------------------------------------
    $generator = "Visual Studio 17 2022"
    $vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
    if (Test-Path $vswhere) {
        $vsPath = & $vswhere -latest -products * `
            -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 `
            -property installationPath 2>$null
        if ($vsPath) {
            if ($vsPath -match '\\18\\' -or $vsPath -match '2026') {
                $generator = "Visual Studio 18 2026"
            } elseif ($vsPath -match '2022') {
                $generator = "Visual Studio 17 2022"
            }
            Write-Host "Visual Studio found: $vsPath"
        } else {
            Write-Host "WARNING: no VS C++ workload found via vswhere; assuming VS 2022 generator."
        }
    } else {
        Write-Host "WARNING: vswhere not found; assuming VS 2022 generator."
    }
    Write-Host "CMake generator: $generator"

    # --- Clean stale cache if it was generated by a different generator ------
    $cache = Join-Path $buildDir "CMakeCache.txt"
    if (Test-Path $cache) {
        $line = Select-String -Path $cache -Pattern '^CMAKE_GENERATOR:INTERNAL=(.+)$' | Select-Object -First 1
        $cachedGen = if ($line) { $line.Matches[0].Groups[1].Value } else { "" }
        if ($Clean -or ($cachedGen -and $cachedGen -ne $generator)) {
            Write-Host "Cleaning build directory ($cachedGen -> $generator)..."
            Remove-Item -Recurse -Force $buildDir -ErrorAction SilentlyContinue
        }
    }

    # --- Configure and build --------------------------------------------------
    cmake -S . -B build -G $generator -A x64
    if ($LASTEXITCODE -ne 0) { throw "CMake configure failed." }

    cmake --build build --config Release --parallel
    if ($LASTEXITCODE -ne 0) { throw "Build failed." }

    Write-Host ""
    Write-Host "BUILD OK -> build\VoicePad_artefacts\Release\VoicePad.exe"
    Write-Host "Route VoicePad OUTPUT to 'CABLE Input' and select 'CABLE Output' in Discord/games."
}
finally {
    Pop-Location
}
